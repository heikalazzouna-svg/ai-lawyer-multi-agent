import asyncio

def get_llm_model(streaming: bool = False):
    api_key = os.getenv("GROQ_API_KEY")
    if not api_key:
        raise EnvironmentError("GROQ_API_KEY is not set.")
    model_name = os.getenv("GROQ_MODEL_NAME", "llama-3.3-70b-versatile")
    # Enable streaming if requested
    return ChatGroq(model=model_name, streaming=streaming)

@semantic_cache(ttl_seconds=3600)
def generate_summary(db: Session, document_id: int) -> str:
    # Retrieve top 10 chunks to summarize the document
    chunks = hybrid_search(db, query="summary abstract key points", document_id=document_id, limit=10)
    context = "\n\n".join([c.content for c in chunks])
    
    prompt = ChatPromptTemplate.from_template(
        "Summarize the given legal document concisely while preserving key details.\n\nDocument:\n{context}\n\nSummary:"
    )
    model = get_llm_model()
    chain = prompt | model
    
    response = chain.invoke({"context": context})
    return str(response.content) if hasattr(response, 'content') else str(response)

async def stream_rag_response(db: Session, session_id: int, document_id: int, query: str):
    """
    Execute a RAG query and stream the response back using Server-Sent Events (SSE).
    Also persists the user message and AI response to the PostgreSQL database.
    """
    # 1. Save user query to DB
    user_msg = ChatMessage(session_id=session_id, role="user", content=query)
    db.add(user_msg)
    db.commit()
    
    # 2. Retrieve Context via Hybrid Search
    chunks = hybrid_search(db, query=query, document_id=document_id)
    context = "\n\n".join([c.content for c in chunks])
    
    # 3. Retrieve Conversation History
    history_msgs = db.query(ChatMessage).filter(ChatMessage.session_id == session_id).order_by(ChatMessage.created_at.asc()).all()
    history = "\n".join([f"{m.role}: {m.content}" for m in history_msgs[:-1]]) # exclude current query
    
    prompt_template = """
    Use the context provided to answer the user's question. If you don't know, say you don't know.
    
    Previous Conversation:
    {history}
    
    Context: {context}
    Question: {question}
    Answer:
    """
    
    prompt = ChatPromptTemplate.from_template(prompt_template)
    model = get_llm_model(streaming=True)
    chain = prompt | model
    
    async def sse_generator():
        full_response = ""
        # stream() yields chunks as they are generated by the LLM
        async for chunk in chain.astream({"history": history, "context": context, "question": query}):
            if chunk.content:
                full_response += chunk.content
                # Format as Server-Sent Event
                yield f"data: {chunk.content}\n\n"
                
        # After streaming completes, save the full response to DB
        ai_msg = ChatMessage(session_id=session_id, role="ai", content=full_response)
        db.add(ai_msg)
        db.commit()
        
        yield "data: [DONE]\n\n"
        
    return StreamingResponse(sse_generator(), media_type="text/event-stream")
